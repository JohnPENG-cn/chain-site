def main():
    it = sources.page_items()
    J = [(k, v) for k, v in it.items() if v['kind'] == '判断']
    P = [(k, v) for k, v in it.items() if v['kind'] == '预测']
    items = []
    for n, (k, v) in enumerate(J, 1):
        items.append(dict(gid=f'G{n:02d}', old=k, kind='判断', chain=v['chain'], book=v['book'], page=v['page'], text=v['text'],
                          status=v['st'], falsify=v['falsify'], th=v['th'], due=v.get('due', ''), prob=None, reason='',
                          outcome='', brier=None))
    for n, (k, v) in enumerate(P, 1):
        p, why = PROB.get(k, (None, ''))
        if v['st'] != '作废':
            assert p is not None, f'缺概率：{k}'
        items.append(dict(gid=f'P{n:03d}', old=k, kind='预测', chain=v['chain'], book=v['book'], page=v['page'], text=v['text'],
                          status=v['st'], falsify=f'到期不成立即为错；验证来源：{v["check"]}', check=v['check'], due=v['due'],
                          prob=p if v['st'] != '作废' else None, reason=why if v['st'] != '作废' else v.get('note', ''),
                          prob_state='初稿' if v['st'] != '作废' else '', outcome='作废' if v['st'] == '作废' else '待验证', brier=None))
    doc = dict(schema='ledger/v1', updated='2026-10-22',
               note='全局判断总账（唯一来源）。判断原文与各研究页一致，不在这里改写；概率为 2026-10-22 初稿，待 John 确认。'
                    '打分：到期后 outcome 填 命中/未中，build.py 自动算 Brier =（概率 − 结果）²，结果命中=1、未中=0。',
               status_legend={'有效': '页面上“未触发”', '受挑战': '页面上“需盯紧”：反方证据接近阈值', '证伪': '证伪条件已触发', '作废': '前提失效，原文保留'},
               items=items)
    out = os.path.join(sources.ROOT, 'data', 'ledger.json')
    assert not os.path.exists(out) or '--force' in sys.argv, 'data/ledger.json 已存在（以它为准）；确需重建加 --force'
    json.dump(doc, open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f'写入 {out}：判断 {len(J)} 条，预测 {len(P)} 条')


if __name__ == '__main__':
    main()
