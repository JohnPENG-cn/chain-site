def dc(y, kw, tpm):
    """AI 数据中心当年用铜（kt）= 加速器（百万颗）× kW/颗 × 吨/MW（百万颗 × kW = GW；GW × 吨/MW = 千吨）"""
    return A[y] * kw * tpm


def calc(p=None):
    p = {**P0, **(p or {})}
    dc26 = dc(2026, KW26, p['tpm']); dc27 = dc(2027, p['kw27'], p['tpm'])
    base26 = ICSG['use'][2026] - dc26
    trad27 = base26 * (1 + p['g27'] / 100)
    ref27 = ICSG['ref'][2027] + p['mine27']          # 精炼受精矿约束：矿山少 1 吨，原生精炼少 1 吨（估）
    use27 = trad27 + dc27 + p['scrap27'] + p['cn27']
    g = {2025: ICSG['bal'][2025], 2026: ICSG['bal'][2026], 2027: ref27 - use27}
    us = {2025: None, 2026: US26, 2027: p['us27']}
    return dict(dc26=dc26, dc27=dc27, ddc=dc27 - dc26, trad27=trad27, dtrad=trad27 - base26, ref27=ref27, use27=use27, gbal=g, exus={2026: g[2026] - US26, 2027: g[2027] - p['us27']},
                ug=(use27 / ICSG['use'][2026] - 1) * 100, kg27=p['kw27'] * p['tpm'], kg26=KW26 * p['tpm'], share_dc=dc27 / use27)


