def agg(y, cos=BOARD):
    cs = [c for c in cos if c['data'].get(y, {}).get('capex') is not None and c['data'][y].get('dep')]
    f = lambda k: sum(c['data'][y].get(k) or 0 for c in cs)
    return dict(n=len(cs), capex=f('capex'), dep=f('dep'), cip=f('cip'), fa=f('fa'), rev=f('rev'))


AGG = {y: agg(y) for y in YRS}
for v in AGG.values():
    v['ratio'] = v['capex'] / v['dep']


def med(seg, y, k):
    v = [c['data'][y][k] for c in FIN['cos'] if c['seg'] == seg and c['data'].get(y, {}).get(k) is not None]
    return st.median(v) if v else None


